def run_pipeline() -> dict[str, Any]:
    started = time.time()
    ensure_dirs()
    r1_audit = r1_handoff_audit()
    datasets = {name: load_dataset(name) for name in ("OpenBMI", "WBCIC")}
    banks: dict[str, pd.DataFrame] = {}
    manifests: dict[str, dict[str, Any]] = {}
    for name, data in datasets.items():
        banks[name], manifests[name] = build_bank(data)
    data_by_dataset = {name: wide_bank(bank, name) for name, bank in banks.items()}
    competence = {name: competence_audit(name, data) for name, data in data_by_dataset.items()}
    write_json(RESULTS / "COMPETENCE_AUDIT.json", {"datasets": list(competence.values()), "all_competent": all(v["competent"] for v in competence.values())})
    if not all(v["competent"] for v in competence.values()):
        metrics = pd.DataFrame()
        per_subject = pd.DataFrame()
        instability = pd.DataFrame()
        complementarity = pd.DataFrame()
        associations: dict[str, Any] = {}
        recipe = (1.0, 0.5)
        terminal = "CPV2_BACKBONE_COMPETENCE_NOT_ESTABLISHED"
        write_protocol_and_reports(r1_audit, manifests, competence, metrics, per_subject, recipe, instability, associations, complementarity, terminal)
        write_figures(metrics, per_subject, instability, associations)
        return {"terminal": terminal, "elapsed_seconds": time.time() - started}
    recipe, _recipe_frame = global_recipe_selection(data_by_dataset)
    metric_frames: list[pd.DataFrame] = []
    per_frames: list[pd.DataFrame] = []
    details_by_dataset: dict[str, dict[str, Any]] = {}
    for name, data in data_by_dataset.items():
        metrics, per_subject, details = evaluate_dataset(name, data, recipe)
        metric_frames.append(metrics); per_frames.append(per_subject); details_by_dataset[name] = details
        write_csv(RESULTS / f"{name}_METRICS.csv", metrics)
    metrics = pd.concat(metric_frames, ignore_index=True)
    per_subject = pd.concat(per_frames, ignore_index=True)
    instability, associations = consensus_audit({name: frame for name, frame in zip(data_by_dataset, metric_frames)}, details_by_dataset)
    complementarity = complementarity_audit(details_by_dataset, metrics)
    write_csv(RESULTS / "CALIBRATION_PARAMETERS.csv", pd.DataFrame(sum((d["calibration_rows"] for d in details_by_dataset.values()), [])))
    write_csv(RESULTS / "FAMILY_STACK_WEIGHTS.csv", pd.DataFrame(sum((d["family_rows"] for d in details_by_dataset.values()), [])))
    write_csv(RESULTS / "CONSENSUS_ALPHA.csv", pd.DataFrame(sum((d["alpha_rows"] for d in details_by_dataset.values()), [])))
    robust_per_fold = metrics[metrics.method.isin(["STRONGEST_KEEP", "BEST_COMPLEMENTARY_STACK", "SUBJECT_ROBUST_STACK"])].copy()
    write_csv(RESULTS / "ROBUST_STACK_PER_FOLD.csv", robust_per_fold)
    comp = metrics[metrics.method.eq("BEST_COMPLEMENTARY_STACK")].set_index("dataset")
    keep = metrics[metrics.method.eq("STRONGEST_KEEP")].set_index("dataset")
    robust = metrics[metrics.method.eq("SUBJECT_ROBUST_STACK")].set_index("dataset")
    complementarity_supported = bool(all((comp.loc[d, "delta_BA_vs_STRONGEST_KEEP"] > 0 and comp.loc[d, "bootstrap_CI95_L"] > 0) for d in data_by_dataset))
    robust_supported = bool(all((robust.loc[d, "delta_BA_vs_STRONGEST_KEEP"] >= 0.005 and robust.loc[d, "bootstrap_CI95_L"] > 0 and robust.loc[d, "positive_subject_fraction"] >= 0.60 and robust.loc[d, "median_subject_delta_BA"] >= 0 and robust.loc[d, "strong_negative_subject_fraction_lt_minus_0p01"] <= 0.15) for d in data_by_dataset))
    consensus_supported = False
    if robust_supported:
        consensus_supported = bool(all(associations.get(d, {}).get("instability_error_association_meaningful", False) for d in data_by_dataset))
    if robust_supported and consensus_supported:
        terminal = "CPV2_CGRSTACK_SOURCE_SUPPORTED"
    elif robust_supported:
        terminal = "CPV2_ROBUST_STACK_SOURCE_SUPPORTED"
    elif complementarity_supported:
        terminal = "CPV2_SOURCE_NOT_SUPPORTED"
    else:
        terminal = "CPV2_COMPLEMENTARITY_NOT_SUPPORTED"
    # Consensus is never promoted merely because its descriptive association is
    # positive; the complete robust source gate is binding and C8 remains a
    # transparent alias until that gate passes.
    write_protocol_and_reports(r1_audit, manifests, competence, metrics, per_subject, recipe, instability, associations, complementarity, terminal)
    write_figures(metrics, per_subject, instability, associations)
    stats = {"terminal": terminal, "selected_recipe": {"lambda_harm": recipe[0], "lambda_tail": recipe[1]}, "complementarity_supported": complementarity_supported, "robust_stack_supported": robust_supported, "consensus_supported": consensus_supported, "S2_accessed": False, "outer_accessed": False, "elapsed_seconds": time.time() - started}
    write_json(RESULTS / "STATISTICS.json", {**json.loads((RESULTS / "STATISTICS.json").read_text(encoding="utf-8")), **stats})
    print(json.dumps(clean(stats), ensure_ascii=False, indent=2), flush=True)
    return stats


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", choices=("all", "audit", "bank"), default="all")
    parser.add_argument("--dataset", choices=("OpenBMI", "WBCIC", "both"), default="both")
    args = parser.parse_args()
    ensure_dirs()
    if args.phase == "audit":
        audit = r1_handoff_audit()
        print(json.dumps(clean(audit), ensure_ascii=False, indent=2), flush=True)
        return
    if args.phase == "bank":
        r1_handoff_audit()
        names = ("OpenBMI", "WBCIC") if args.dataset == "both" else (args.dataset,)
        for name in names:
            data = load_dataset(name)
            _bank, manifest = build_bank(data)
            print(json.dumps(clean(manifest), ensure_ascii=False, indent=2), flush=True)
        return
    run_pipeline()


if __name__ == "__main__":
    main()
