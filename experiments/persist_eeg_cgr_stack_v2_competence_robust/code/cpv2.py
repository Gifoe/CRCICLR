def wide_bank(bank: pd.DataFrame, dataset: str) -> dict[str, Any]:
    target = bank[bank.session.eq(1)].copy() if dataset == "WBCIC" else bank.copy()
    target["margin"] = target.logit_1.astype(float) - target.logit_0.astype(float)
    sample_ids = sorted(target.sample_id.astype(str).unique())
    margins: dict[str, np.ndarray] = {}
    for expert in EXPERTS:
        lookup = target[target.expert.eq(expert)].set_index(["sample_id", "slot"])["margin"]
        margins[expert] = np.asarray([[float(lookup.loc[(sid, slot)]) for slot in RUN_SLOTS] for sid in sample_ids], dtype=float)
    meta = target.drop_duplicates("sample_id").set_index("sample_id").loc[sample_ids]
    return {"sample_ids": np.asarray(sample_ids), "subjects": meta.subject.astype(str).to_numpy(), "sessions": meta.session.astype(int).to_numpy(), "y": meta.label.astype(int).to_numpy(), "margins": margins}


def outer_folds(subjects: np.ndarray, salt: str) -> dict[str, int]:
    return partition_subjects(subjects, salt)


def inner_split(subjects: np.ndarray, dataset: str) -> tuple[set[str], set[str]]:
    assignments = {s: int(stable_unit(INNER_SALTS[dataset], s) >= 0.30) for s in subject_ids(subjects)}
    train = {s for s, group in assignments.items() if group == 0}
    val = set(assignments) - train
    if len(train) < 3 or len(val) < 2:
        ordered = subject_ids(subjects)
        split = max(2, int(len(ordered) * 0.7))
        train, val = set(ordered[:split]), set(ordered[split:])
    return train, val


def fit_temperature(margins: np.ndarray, y: np.ndarray, subjects: np.ndarray) -> float:
    margins = np.asarray(margins, dtype=float)
    y_flat = np.repeat(np.asarray(y).astype(int), margins.shape[1])
    s_flat = np.repeat(np.asarray(subjects).astype(str), margins.shape[1])
    weights = np.repeat(subject_weights(subjects, y), margins.shape[1])
    flat = margins.reshape(-1)

    def objective(log_t: float) -> float:
        p = sigmoid(flat / math.exp(float(log_t)))
        loss = -(y_flat * np.log(np.clip(p, 1e-6, 1 - 1e-6)) + (1 - y_flat) * np.log(np.clip(1 - p, 1e-6, 1 - 1e-6)))
        return float(np.average(loss, weights=weights))

    result = minimize_scalar(objective, bounds=(math.log(0.1), math.log(10.0)), method="bounded", options={"xatol": 1e-5})
    return float(np.clip(math.exp(float(result.x)), 0.1, 10.0))


def fit_per_run_temperatures(margins: np.ndarray, y: np.ndarray, subjects: np.ndarray) -> np.ndarray:
    return np.asarray([fit_temperature(np.asarray(margins)[:, r : r + 1], y, subjects) for r in range(np.asarray(margins).shape[1])], dtype=float)


def choose_temperature(margins: np.ndarray, y: np.ndarray, subjects: np.ndarray) -> tuple[np.ndarray, str, float, float]:
    # Per-run temperatures are the declared primary calibration; a single
    # family-shared scalar is evaluated as a low-variance control.
    per = fit_per_run_temperatures(margins, y, subjects)
    shared = fit_temperature(margins, y, subjects)
    p_per = sigmoid(margins / per[None, :])
    p_shared = sigmoid(margins / shared)
    loss_per = -(y[:, None] * np.log(np.clip(p_per, 1e-6, 1 - 1e-6)) + (1 - y[:, None]) * np.log(np.clip(1 - p_per, 1e-6, 1 - 1e-6))).mean(axis=1)
    loss_shared = -(y[:, None] * np.log(np.clip(p_shared, 1e-6, 1 - 1e-6)) + (1 - y[:, None]) * np.log(np.clip(1 - p_shared, 1e-6, 1 - 1e-6))).mean(axis=1)
    best = float(min(loss_per.mean(), loss_shared.mean()))
    se = float(np.std(loss_per if loss_per.mean() <= loss_shared.mean() else loss_shared, ddof=1) / math.sqrt(max(len(loss_per), 1)))
    if loss_shared.mean() <= best + se:
        return np.full(margins.shape[1], shared, dtype=float), "family_shared_one_se", float(loss_per.mean()), float(loss_shared.mean())
    return per, "per_run", float(loss_per.mean()), float(loss_shared.mean())


def fit_simplex(x: np.ndarray, y: np.ndarray, subjects: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y).astype(int)
    weights = subject_weights(subjects, y)
    init = np.full(x.shape[1], 1.0 / x.shape[1])

    def objective(w: np.ndarray) -> float:
        p = sigmoid(x @ w)
        loss = -(y * np.log(np.clip(p, 1e-6, 1 - 1e-6)) + (1 - y) * np.log(np.clip(1 - p, 1e-6, 1 - 1e-6)))
        return float(np.average(loss, weights=weights) + 1e-3 * np.sum(w * w))

    result = minimize(objective, init, method="SLSQP", bounds=[(0.0, 1.0)] * x.shape[1], constraints={"type": "eq", "fun": lambda w: float(w.sum() - 1.0)}, options={"maxiter": 500, "ftol": 1e-10})
    if not result.success:
        return init
    w = np.clip(result.x, 0.0, 1.0)
    return w / max(float(w.sum()), 1e-12)


def logistic_fit_predict(x_train: np.ndarray, y_train: np.ndarray, s_train: np.ndarray, x_all: np.ndarray) -> np.ndarray:
    if len(np.unique(y_train)) < 2:
        return np.full(len(x_all), float(np.mean(y_train) >= 0.5))
    model = LogisticRegression(max_iter=2000, solver="lbfgs", C=1.0, random_state=BASE_SEED)
    model.fit(x_train, y_train, sample_weight=subject_weights(s_train, y_train))
    return model.predict_proba(x_all)[:, 1]


def instability_groups(keep_margins: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    votes = (np.asarray(keep_margins) >= 0).sum(axis=1)
    fraction = votes / keep_margins.shape[1]
    entropy = -(np.clip(fraction, 1e-8, 1 - 1e-8) * np.log(np.clip(fraction, 1e-8, 1 - 1e-8)) + np.clip(1 - fraction, 1e-8, 1 - 1e-8) * np.log(np.clip(1 - fraction, 1e-8, 1 - 1e-8)))
    group = np.where((votes == 0) | (votes == 6), 0, np.where((votes == 1) | (votes == 5), 1, np.where((votes == 2) | (votes == 4), 2, 3)))
    return group.astype(int), entropy.astype(float), votes.astype(int)


def balanced_logloss_per_subject(y: np.ndarray, probability: np.ndarray, subjects: np.ndarray) -> np.ndarray:
    y = np.asarray(y).astype(int)
    p = np.clip(np.asarray(probability, dtype=float), 1e-6, 1 - 1e-6)
    loss = -(y * np.log(p) + (1 - y) * np.log1p(-p))
    s = np.asarray(subjects).astype(str)
    return np.asarray([float(loss[s == sub].mean()) for sub in subject_ids(s)], dtype=float)


def robust_score(utility: np.ndarray) -> float:
    utility = np.asarray(utility, dtype=float)
    return float(utility.mean() - 0.5 * utility.std(ddof=1) + 0.5 * np.quantile(utility, 0.25)) if len(utility) > 1 else float(utility.mean())


def fit_residual_alpha(anchor_logit: np.ndarray, stack_logit: np.ndarray, y: np.ndarray, subjects: np.ndarray,
                       lambda_harm: float, lambda_tail: float) -> tuple[float, dict[str, float]]:
    anchor_logit = np.asarray(anchor_logit, dtype=float)
    stack_logit = np.asarray(stack_logit, dtype=float)
    y = np.asarray(y).astype(int)
    subject_values = np.asarray(subjects).astype(str)
    def objective(alpha: float) -> float:
        final = sigmoid(anchor_logit + float(alpha) * (stack_logit - anchor_logit))
        utility = balanced_logloss_per_subject(y, sigmoid(anchor_logit), subject_values) - balanced_logloss_per_subject(y, final, subject_values)
        harm = -utility
        positive_harm = np.maximum(harm, 0.0)
        tail_n = max(1, int(math.ceil(len(harm) * 0.25)))
        cvar = float(np.sort(harm)[-tail_n:].mean())
        return float(-utility.mean() + lambda_harm * positive_harm.mean() + lambda_tail * cvar + 1e-3 * alpha * alpha)
    opt = minimize_scalar(objective, bounds=(0.0, 1.0), method="bounded", options={"xatol": 1e-6})
    alpha = float(np.clip(opt.x if opt.success else 0.0, 0.0, 1.0))
    final = sigmoid(anchor_logit + alpha * (stack_logit - anchor_logit))
    utility = balanced_logloss_per_subject(y, sigmoid(anchor_logit), subject_values) - balanced_logloss_per_subject(y, final, subject_values)
    harm = -utility
    return alpha, {"alpha": alpha, "mean_utility": float(utility.mean()), "fraction_harmed": float(np.mean(harm > 0)), "mean_harm_harmed": float(np.mean(harm[harm > 0])) if np.any(harm > 0) else 0.0, "worst_quartile_utility": float(np.quantile(utility, 0.25)), "utility_sd": float(np.std(utility, ddof=1)) if len(utility) > 1 else 0.0, "robust_score": robust_score(utility)}


def fit_all_params(data: dict[str, Any], train_mask: np.ndarray) -> dict[str, Any]:
    y = data["y"]
    subjects = data["subjects"]
    margins = data["margins"]
    temperatures: dict[str, np.ndarray] = {}
    temperature_mode: dict[str, str] = {}
    temperature_losses: list[dict[str, Any]] = []
    calibrated: dict[str, np.ndarray] = {}
    for expert in EXPERTS:
        t, mode, per_loss, shared_loss = choose_temperature(margins[expert][train_mask], y[train_mask], subjects[train_mask])
        temperatures[expert] = t
        temperature_mode[expert] = mode
        calibrated[expert] = margins[expert] / t[None, :]
        temperature_losses.append({"expert": expert, "temperature": t, "selection": mode, "per_run_train_logloss": per_loss, "family_shared_train_logloss": shared_loss})
    family_equal = {expert: calibrated[expert].mean(axis=1) for expert in EXPERTS}
    family_weights: dict[str, np.ndarray] = {}
    family_simplex: dict[str, np.ndarray] = {}
    for expert in EXPERTS:
        weights = fit_simplex(calibrated[expert][train_mask], np.repeat(y[train_mask], 1), subjects[train_mask])
        family_weights[expert] = weights
        family_simplex[expert] = calibrated[expert] @ weights
    family_matrix = np.column_stack([family_equal[e] for e in EXPERTS])
    family_simplex_matrix = np.column_stack([family_simplex[e] for e in EXPERTS])
    all_logits = np.column_stack([calibrated[e] for e in EXPERTS for _ in (0,)])
    # B0 uses a single KEEP run selected using training-subject BA only.
    b0_scores = [balanced_accuracy_score(y[train_mask], (calibrated["E0_KEEP_ERM"][train_mask, r] >= 0).astype(int)) for r in RUN_SLOTS]
    b0_run = int(np.argmax(b0_scores))
    b0_logit = calibrated["E0_KEEP_ERM"][:, b0_run]
    b1_logit = calibrated["E0_KEEP_ERM"].mean(axis=1)
    b2_logit = calibrated["E0_KEEP_ERM"].mean(axis=1)
    b3_logit = family_simplex["E0_KEEP_ERM"]
    b4_logit = family_matrix.mean(axis=1)
    b5_weights = fit_simplex(family_matrix[train_mask], y[train_mask], subjects[train_mask])
    b5_logit = family_matrix @ b5_weights
    b6_prob = logistic_fit_predict(family_matrix[train_mask], y[train_mask], subjects[train_mask], family_matrix)
    b6_logit = logit(b6_prob)
    all18 = np.column_stack([calibrated[e] for e in EXPERTS])
    b7_prob = logistic_fit_predict(all18[train_mask], y[train_mask], subjects[train_mask], all18)
    b7_logit = logit(b7_prob)
    candidates = {
        "B0_BEST_SINGLE_KEEP": b0_logit,
        "B1_SIX_RUN_MAJORITY_KEEP": b1_logit,
        "B2_EQUAL_CALIBRATED_KEEP": b2_logit,
        "B3_LEARNED_KEEP_FAMILY_STACK": b3_logit,
        "B4_EQUAL_ALL_FAMILY": b4_logit,
        "B5_THREE_FAMILY_SIMPLEX_STACK": b5_logit,
        "B6_THREE_FAMILY_LOGISTIC_STACK": b6_logit,
        "B7_18_LOGIT_LOGISTIC_STACK": b7_logit,
    }
    return {
        "temperatures": temperatures,
        "temperature_mode": temperature_mode,
        "temperature_losses": temperature_losses,
        "calibrated": calibrated,
        "family_equal": family_equal,
        "family_weights": family_weights,
        "family_matrix": family_matrix,
        "family_simplex_weights": b5_weights,
        "candidates": candidates,
        "all18": all18,
    }


def select_candidate(params: dict[str, Any], data: dict[str, Any], indices: np.ndarray, names: list[str]) -> str:
    y = data["y"][indices]
    subjects = data["subjects"][indices]
    scores = []
    for name in names:
        pred = (params["candidates"][name][indices] >= 0).astype(int)
        scores.append((float(balanced_accuracy_score(y, pred)), name))
    best = max(scores)[0]
    # One-standard-error style simplicity tie: preserve preregistered order.
    eligible = [name for score, name in scores if score >= best - 0.005]
    return eligible[0] if eligible else max(scores)[1]


def make_nested_params(data: dict[str, Any], outer_train: np.ndarray, dataset: str) -> tuple[dict[str, Any], str, str]:
    subjects = data["subjects"]
    train_subjects = set(subjects[outer_train])
    inner_train_subjects, inner_val_subjects = inner_split(subjects[outer_train], dataset)
    inner_train = outer_train & np.isin(subjects, list(inner_train_subjects))
    inner_val = outer_train & np.isin(subjects, list(inner_val_subjects))
    inner_params = fit_all_params(data, inner_train)
    keep_names = ["B0_BEST_SINGLE_KEEP", "B1_SIX_RUN_MAJORITY_KEEP", "B2_EQUAL_CALIBRATED_KEEP", "B3_LEARNED_KEEP_FAMILY_STACK"]
    comp_names = ["B4_EQUAL_ALL_FAMILY", "B5_THREE_FAMILY_SIMPLEX_STACK", "B6_THREE_FAMILY_LOGISTIC_STACK", "B7_18_LOGIT_LOGISTIC_STACK"]
    keep_choice = select_candidate(inner_params, data, inner_val, keep_names)
    comp_choice = select_candidate(inner_params, data, inner_val, comp_names)
    params = fit_all_params(data, outer_train)
    return params, keep_choice, comp_choice


def global_recipe_selection(data_by_dataset: dict[str, dict[str, Any]]) -> tuple[tuple[float, float], pd.DataFrame]:
    rows: list[dict[str, Any]] = []
    per_dataset: dict[str, dict[tuple[float, float], float]] = {}
    for dataset, data in data_by_dataset.items():
        train_subjects, val_subjects = inner_split(data["subjects"], dataset)
        train = np.isin(data["subjects"], list(train_subjects))
        val = np.isin(data["subjects"], list(val_subjects))
        params = fit_all_params(data, train)
        keep = params["candidates"]["B3_LEARNED_KEEP_FAMILY_STACK"]
        stack = params["candidates"]["B6_THREE_FAMILY_LOGISTIC_STACK"]
        scores: dict[tuple[float, float], float] = {}
        for lambda_harm in LAMBDA_HARM_GRID:
            for lambda_tail in LAMBDA_TAIL_GRID:
                alpha, detail = fit_residual_alpha(keep[train], stack[train], data["y"][train], data["subjects"][train], lambda_harm, lambda_tail)
                final_val = keep[val] + alpha * (stack[val] - keep[val])
                utility = balanced_logloss_per_subject(data["y"][val], sigmoid(keep[val]), data["subjects"][val]) - balanced_logloss_per_subject(data["y"][val], sigmoid(final_val), data["subjects"][val])
                score = robust_score(utility)
                scores[(lambda_harm, lambda_tail)] = score
                rows.append({"dataset": dataset, "lambda_harm": lambda_harm, "lambda_tail": lambda_tail, "alpha_inner": alpha, "mean_subject_utility": float(utility.mean()), "fraction_harmed": float(np.mean(utility < 0)), "worst_quartile_utility": float(np.quantile(utility, 0.25)), "utility_sd": float(np.std(utility, ddof=1)) if len(utility) > 1 else 0.0, "RobustScore": score, "selection_unit": "biological_subject_inner_validation"})
        per_dataset[dataset] = scores
    candidates = sorted({key for values in per_dataset.values() for key in values})
    chosen = max(candidates, key=lambda key: (min(per_dataset[d].get(key, -np.inf) for d in per_dataset), -sum(key), -key[0], -key[1]))
    frame = pd.DataFrame(rows)
    frame["selected_global_same_recipe"] = frame.apply(lambda row: float(row.lambda_harm) == chosen[0] and float(row.lambda_tail) == chosen[1], axis=1)
    frame.to_csv(RESULTS / "ROBUST_RECIPE_SEARCH.csv", index=False)
    return chosen, frame


def evaluate_dataset(dataset: str, data: dict[str, Any], selected_recipe: tuple[float, float]) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    y = data["y"]
    subjects = data["subjects"]
    folds = outer_folds(subjects, OUTER_SALTS[dataset])
    fold_ids = np.asarray([folds[s] for s in subjects], dtype=int)
    n = len(y)
    method_names = [
        "B0_BEST_SINGLE_KEEP", "B1_SIX_RUN_MAJORITY_KEEP", "B2_EQUAL_CALIBRATED_KEEP", "B3_LEARNED_KEEP_FAMILY_STACK",
        "B4_EQUAL_ALL_FAMILY", "B5_THREE_FAMILY_SIMPLEX_STACK", "B6_THREE_FAMILY_LOGISTIC_STACK", "B7_18_LOGIT_LOGISTIC_STACK",
        "STRONGEST_KEEP", "BEST_COMPLEMENTARY_STACK", "SUBJECT_ROBUST_STACK",
        "C0_KEEP_LOGISTIC_MATCHED", "C1_DUPLICATE_KEEP_STACK", "C2_PERMUTED_FAMILY_IDENTITY", "C3_EQUAL_ALL_EXPERT_AVERAGING",
        "C4_UNCONSTRAINED_ALL_EXPERT_LOGISTIC", "C5_ROBUST_NO_HARM_PENALTY", "C6_ROBUST_NO_CVAR", "C7_FINAL_SUBJECT_ROBUST_STACK", "C8_CONSENSUS_GUIDED_STACK",
    ]
    predictions = {name: np.zeros(n, dtype=float) for name in method_names}
    alpha_rows: list[dict[str, Any]] = []
    calibration_rows: list[dict[str, Any]] = []
    family_rows: list[dict[str, Any]] = []
    subject_rows: list[dict[str, Any]] = []
    instability_rows: list[dict[str, Any]] = []
    keep_anchor_logits = np.zeros(n, dtype=float)
    comp_stack_logits = np.zeros(n, dtype=float)
    groups_all = np.zeros(n, dtype=int)
    # Consensus is not allowed until the stacking core has passed on both
    # datasets.  We still compute its descriptive instability/error table.
    for fold in range(5):
        train = fold_ids != fold
        held = ~train
        params, keep_choice, comp_choice = make_nested_params(data, train, dataset)
        keep_logit = params["candidates"][keep_choice]
        comp_logit = params["candidates"][comp_choice]
        keep_anchor_logits[held] = keep_logit[held]
        comp_stack_logits[held] = comp_logit[held]
        group, entropy, votes = instability_groups(data["margins"]["E0_KEEP_ERM"])
        groups_all[held] = group[held]
        alpha, alpha_detail = fit_residual_alpha(keep_logit[train], comp_logit[train], y[train], subjects[train], selected_recipe[0], selected_recipe[1])
        alpha_no_harm, _ = fit_residual_alpha(keep_logit[train], comp_logit[train], y[train], subjects[train], 0.0, selected_recipe[1])
        alpha_no_cvar, _ = fit_residual_alpha(keep_logit[train], comp_logit[train], y[train], subjects[train], selected_recipe[0], 0.0)
        robust_logit = keep_logit + alpha * (comp_logit - keep_logit)
        no_harm_logit = keep_logit + alpha_no_harm * (comp_logit - keep_logit)
        no_cvar_logit = keep_logit + alpha_no_cvar * (comp_logit - keep_logit)
        # C0–C4 are matched diagnostics fitted only on outer-training subjects.
        c0_prob = logistic_fit_predict(params["calibrated"]["E0_KEEP_ERM"][train], y[train], subjects[train], params["calibrated"]["E0_KEEP_ERM"])
        c1_features = np.column_stack([params["calibrated"]["E0_KEEP_ERM"]] * 3)
        c1_prob = logistic_fit_predict(c1_features[train], y[train], subjects[train], c1_features)
        rng = np.random.default_rng(stable_seed("CPV2_PERMUTED_FAMILY", dataset, fold))
        perm = rng.permutation(3)
        perm_train = params["family_matrix"][train][:, perm]
        perm_all = params["family_matrix"][:, perm]
        c2_prob = logistic_fit_predict(perm_train, y[train], subjects[train], perm_all)
        c3_logit = params["family_matrix"].mean(axis=1)
        c4_prob = logistic_fit_predict(params["all18"][train], y[train], subjects[train], params["all18"])
        fold_logits = {
            "B0_BEST_SINGLE_KEEP": params["candidates"]["B0_BEST_SINGLE_KEEP"],
            "B1_SIX_RUN_MAJORITY_KEEP": params["candidates"]["B1_SIX_RUN_MAJORITY_KEEP"],
            "B2_EQUAL_CALIBRATED_KEEP": params["candidates"]["B2_EQUAL_CALIBRATED_KEEP"],
            "B3_LEARNED_KEEP_FAMILY_STACK": params["candidates"]["B3_LEARNED_KEEP_FAMILY_STACK"],
            "B4_EQUAL_ALL_FAMILY": params["candidates"]["B4_EQUAL_ALL_FAMILY"],
            "B5_THREE_FAMILY_SIMPLEX_STACK": params["candidates"]["B5_THREE_FAMILY_SIMPLEX_STACK"],
            "B6_THREE_FAMILY_LOGISTIC_STACK": params["candidates"]["B6_THREE_FAMILY_LOGISTIC_STACK"],
            "B7_18_LOGIT_LOGISTIC_STACK": params["candidates"]["B7_18_LOGIT_LOGISTIC_STACK"],
            "STRONGEST_KEEP": keep_logit,
            "BEST_COMPLEMENTARY_STACK": comp_logit,
            "SUBJECT_ROBUST_STACK": robust_logit,
            "C0_KEEP_LOGISTIC_MATCHED": logit(c0_prob),
            "C1_DUPLICATE_KEEP_STACK": logit(c1_prob),
            "C2_PERMUTED_FAMILY_IDENTITY": logit(c2_prob),
            "C3_EQUAL_ALL_EXPERT_AVERAGING": c3_logit,
            "C4_UNCONSTRAINED_ALL_EXPERT_LOGISTIC": logit(c4_prob),
            "C5_ROBUST_NO_HARM_PENALTY": no_harm_logit,
            "C6_ROBUST_NO_CVAR": no_cvar_logit,
            "C7_FINAL_SUBJECT_ROBUST_STACK": robust_logit,
            # C8 is filled with the robust stack until/if the cross-dataset
            # source gate authorizes consensus; it is never used for fitting.
            "C8_CONSENSUS_GUIDED_STACK": robust_logit,
        }
        for name, values in fold_logits.items():
            predictions[name][held] = sigmoid(values[held])
        alpha_rows.extend([
            {"dataset": dataset, "outer_fold": fold, "lambda_harm": selected_recipe[0], "lambda_tail": selected_recipe[1], "alpha": alpha, "variant": "subject_robust"},
            {"dataset": dataset, "outer_fold": fold, "lambda_harm": 0.0, "lambda_tail": selected_recipe[1], "alpha": alpha_no_harm, "variant": "no_harm_penalty"},
            {"dataset": dataset, "outer_fold": fold, "lambda_harm": selected_recipe[0], "lambda_tail": 0.0, "alpha": alpha_no_cvar, "variant": "no_cvar"},
        ])
        for row in params["temperature_losses"]:
            calibration_rows.append({"dataset": dataset, "outer_fold": fold, **row})
        for expert in EXPERTS:
            family_rows.extend({"dataset": dataset, "outer_fold": fold, "family": expert, "run_slot": slot, "weight": float(weight)} for slot, weight in enumerate(params["family_weights"][expert]))
        for g in range(4):
            mask = held & (group == g)
            if mask.any():
                instability_rows.append({"dataset": dataset, "outer_fold": fold, "group": g, "n": int(mask.sum()), "keep_error": float(np.mean((keep_logit[mask] >= 0) != y[mask])), "vote_entropy": float(entropy[mask].mean()), "mean_margin_variance": float(np.var(data["margins"]["E0_KEEP_ERM"][mask], axis=1).mean()), "pairwise_disagreement": float(np.mean([np.mean(data["margins"]["E0_KEEP_ERM"][i] * data["margins"]["E0_KEEP_ERM"][i] < 0) for i in np.flatnonzero(mask)]))})
        # Per-subject explanatory fields are written for the anchor/stack pair;
        # no subject is filtered or used to change the method.
        for sub in subject_ids(subjects[held]):
            mask = held & (subjects == sub)
            disagreement = float(np.mean(data["margins"]["E0_KEEP_ERM"][mask] >= 0, axis=1).var())
            subject_rows.append({"dataset": dataset, "outer_fold": fold, "subject": sub, "baseline_BA": float(subject_ba(y[mask], (keep_logit[mask] >= 0).astype(int), subjects[mask]).BA.iloc[0]), "stack_BA": float(subject_ba(y[mask], (comp_logit[mask] >= 0).astype(int), subjects[mask]).BA.iloc[0]), "robust_BA": float(subject_ba(y[mask], (robust_logit[mask] >= 0).astype(int), subjects[mask]).BA.iloc[0]), "expert_disagreement_rate": disagreement, "consensus_instability_rate": float(np.mean(group[mask] > 0)), "keep_confidence": float(np.mean(np.abs(sigmoid(data["margins"]["E0_KEEP_ERM"][mask]) - 0.5) * 2)), "keep_calibration_error": float(np.mean(np.abs(sigmoid(data["margins"]["E0_KEEP_ERM"][mask]) - y[mask, None]))), "session_shift_magnitude": float("nan")})
    anchor = predictions["STRONGEST_KEEP"]
    metric_rows: list[dict[str, Any]] = []
    per_subject_rows: list[pd.DataFrame] = []
    for name in method_names:
        row, table = metric_row(dataset, name, y, predictions[name], subjects, anchor)
        metric_rows.append(row)
        per_subject_rows.append(table)
