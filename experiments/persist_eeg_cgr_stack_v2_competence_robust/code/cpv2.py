def stable_unit(*parts: object) -> float:
    raw = "|".join(map(str, parts)).encode("utf-8")
    return int.from_bytes(hashlib.sha256(raw).digest()[:8], "big") / 2**64


def stable_seed(*parts: object) -> int:
    raw = "|".join(map(str, parts)).encode("utf-8")
    return int.from_bytes(hashlib.sha256(raw).digest()[:4], "little")


def set_seed(seed: int) -> None:
    random.seed(int(seed))
    np.random.seed(int(seed) % (2**32 - 1))
    torch.manual_seed(int(seed))
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(int(seed))


def sigmoid(value: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-np.clip(np.asarray(value, dtype=float), -50.0, 50.0)))


def logit(probability: np.ndarray) -> np.ndarray:
    p = np.clip(np.asarray(probability, dtype=float), 1e-6, 1.0 - 1e-6)
    return np.log(p) - np.log1p(-p)


def subject_ids(values: Iterable[object]) -> list[str]:
    return sorted({str(v) for v in values}, key=lambda x: (int(x) if x.isdigit() else 10**9, x))


def subject_weights(subjects: np.ndarray, labels: np.ndarray | None = None) -> np.ndarray:
    """Subject-balanced, and optionally class-balanced, row weights."""
    s = np.asarray(subjects).astype(str)
    y = None if labels is None else np.asarray(labels).astype(int)
    weights = np.zeros(len(s), dtype=float)
    n_subjects = max(len(np.unique(s)), 1)
    for sub in subject_ids(s):
        mask = s == sub
        if y is None:
            weights[mask] = 1.0 / (n_subjects * max(mask.sum(), 1))
            continue
        for cls in (0, 1):
            cmask = mask & (y == cls)
            if cmask.any():
                weights[cmask] = 1.0 / (n_subjects * 2.0 * max(cmask.sum(), 1))
    return weights


def subject_bootstrap(values: np.ndarray, seed: int) -> tuple[float, float]:
    values = np.asarray(values, dtype=float)
    if len(values) == 0:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(int(seed))
    draws = rng.choice(values, size=(BOOTSTRAP_DRAWS, len(values)), replace=True).mean(axis=1)
    return tuple(map(float, np.quantile(draws, [0.025, 0.975])))


def subject_ba(y: np.ndarray, prediction: np.ndarray, subjects: np.ndarray) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    y = np.asarray(y).astype(int)
    pred = np.asarray(prediction).astype(int)
    s = np.asarray(subjects).astype(str)
    for sub in subject_ids(s):
        mask = s == sub
        rows.append({
            "subject": sub,
            "BA": float(balanced_accuracy_score(y[mask], pred[mask])),
            "macro_f1": float(f1_score(y[mask], pred[mask], average="macro", zero_division=0)),
            "n": int(mask.sum()),
        })
    return pd.DataFrame(rows)


def subject_ce(y: np.ndarray, probability: np.ndarray, subjects: np.ndarray) -> pd.DataFrame:
    y = np.asarray(y).astype(int)
    p = np.clip(np.asarray(probability, dtype=float), 1e-6, 1.0 - 1e-6)
    s = np.asarray(subjects).astype(str)
    row_loss = -(y * np.log(p) + (1 - y) * np.log1p(-p))
    return pd.DataFrame({"subject": subject_ids(s), "CE": [float(row_loss[s == sub].mean()) for sub in subject_ids(s)]})


def metric_row(dataset: str, method: str, y: np.ndarray, probability: np.ndarray,
               subjects: np.ndarray, anchor: np.ndarray) -> tuple[dict[str, Any], pd.DataFrame]:
    pred = (np.asarray(probability) >= 0.5).astype(int)
    anchor_pred = (np.asarray(anchor) >= 0.5).astype(int)
    table = subject_ba(y, pred, subjects).set_index("subject")
    anchor_table = subject_ba(y, anchor_pred, subjects).set_index("subject")
    common = table.index.intersection(anchor_table.index)
    delta = (table.loc[common, "BA"] - anchor_table.loc[common, "BA"]).to_numpy(float)
    ci_l, ci_u = subject_bootstrap(delta, stable_seed(dataset, method, "paired_subject_ba"))
    q25 = float(np.quantile(delta, 0.25)) if len(delta) else float("nan")
    worst = float(np.mean(np.sort(delta)[: max(1, int(math.ceil(len(delta) * 0.25))) ])) if len(delta) else float("nan")
    row = {
        "dataset": dataset,
        "method": method,
        "BA": float(table.BA.mean()),
        "trial_BA": float(balanced_accuracy_score(y, pred)),
        "macro_F1": float(table.macro_f1.mean()),
        "delta_BA_vs_STRONGEST_KEEP": float(delta.mean()) if len(delta) else float("nan"),
        "bootstrap_CI95_L": ci_l,
        "bootstrap_CI95_U": ci_u,
        "positive_subject_fraction": float(np.mean(delta > 0)) if len(delta) else float("nan"),
        "negative_subject_fraction": float(np.mean(delta < 0)) if len(delta) else float("nan"),
        "strong_negative_subject_fraction_lt_minus_0p01": float(np.mean(delta < -0.01)) if len(delta) else float("nan"),
        "nonnegative_subject_fraction": float(np.mean(delta >= 0)) if len(delta) else float("nan"),
        "median_subject_delta_BA": float(np.median(delta)) if len(delta) else float("nan"),
        "subject_delta_SD": float(np.std(delta, ddof=1)) if len(delta) > 1 else 0.0,
        "subject_delta_Q25": q25,
        "worst_quartile_mean_delta_BA": worst,
        "subjects": int(len(delta)),
        "OUTER_TEST_USED": False,
    }
    per = table.reset_index().rename(columns={"BA": "final_BA"})
    per["baseline_BA"] = per.subject.map(anchor_table.BA)
    per["delta_BA"] = per.final_BA - per.baseline_BA
    per["dataset"] = dataset
    per["method"] = method
    return row, per


class StandardEEGNet(nn.Module):
    """The fixed EEGNet family used by all three CPV2 experts."""

    def __init__(self, channels: int) -> None:
        super().__init__()
        self.channels = int(channels)
        self.temporal = nn.Conv2d(1, 8, (1, 64), padding="same", bias=False)
        self.bn1 = nn.BatchNorm2d(8)
        self.spatial = nn.Conv2d(8, 16, (self.channels, 1), groups=8, bias=False)
        self.bn2 = nn.BatchNorm2d(16)
        self.pool1 = nn.AvgPool2d((1, 4))
        self.drop1 = nn.Dropout(0.25)
        self.depth = nn.Conv2d(16, 16, (1, 16), padding="same", groups=16, bias=False)
        self.point = nn.Conv2d(16, 16, 1, bias=False)
        self.bn3 = nn.BatchNorm2d(16)
        self.pool2 = nn.AvgPool2d((1, 8))
        self.drop2 = nn.Dropout(0.25)
        with torch.no_grad():
            probe = torch.zeros(2, self.channels, 1000)
            width = self._features_without_embedding(probe).shape[-1]
        self.representation_dim = 64 if self.channels >= 60 else 32
        # ``width`` is already the flattened feature dimension returned by the
        # probe (the 16-channel factor is included in it).
        self.embedding = nn.Sequential(nn.Linear(width, self.representation_dim), nn.ELU(), nn.LayerNorm(self.representation_dim))
        self.head = nn.Linear(self.representation_dim, 2)

    def _features_without_embedding(self, x: torch.Tensor) -> torch.Tensor:
        value = x.unsqueeze(1)
        value = self.bn1(self.temporal(value))
        value = self.drop1(self.pool1(F.elu(self.bn2(self.spatial(value)))))
        value = self.drop2(self.pool2(F.elu(self.bn3(self.point(self.depth(value))))))
        return value.flatten(1)

    def forward_features(self, x: torch.Tensor) -> torch.Tensor:
        return self.embedding(self._features_without_embedding(x))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.head(self.forward_features(x))


class GradientReverse(torch.autograd.Function):
    @staticmethod
    def forward(ctx: Any, x: torch.Tensor) -> torch.Tensor:
        return x.view_as(x)

    @staticmethod
    def backward(ctx: Any, grad_output: torch.Tensor) -> tuple[torch.Tensor]:
        return (-grad_output,)


def coral_penalty(features: torch.Tensor, domains: torch.Tensor) -> torch.Tensor:
    covariances: list[torch.Tensor] = []
    for domain in torch.unique(domains, sorted=True):
        h = features[domains == domain].float()
        if len(h) < 2:
            continue
        h = h - h.mean(0, keepdim=True)
        covariances.append(h.T @ h / (len(h) - 1))
    if len(covariances) < 2:
        return features.new_zeros(())
    cov = torch.stack(covariances)
    centered = cov - cov.mean(0, keepdim=True)
    return centered.square().mean()


class DatasetData:
    def __init__(self, name: str, frame: pd.DataFrame, store: Any, channels: int, status: dict[str, Any]) -> None:
        self.name = name
        self.frame = frame.reset_index(drop=True)
        self.store = store
        self.channels = int(channels)
        self.status = status
        self.subjects = np.asarray(self.frame.subject.astype(str))
        self.labels = self.frame.label.to_numpy(np.int64)
        self.sample_ids = self.frame.sample_id.astype(str).to_numpy()


def load_dataset(name: str) -> DatasetData:
    if name == "OpenBMI":
        frame, store, channels, status = R1.load_openbmi()
    elif name == "WBCIC":
        frame, store, channels, status = R1.load_wbcic_s01()
    else:
        raise ValueError(name)
    return DatasetData(name, frame, store, channels, status)


def partition_subjects(subject_values: Iterable[object], salt: str) -> dict[str, int]:
    subs = subject_ids(subject_values)
    ordered = sorted(subs, key=lambda s: stable_unit(salt, s))
    return {s: int(i % 5) for i, s in enumerate(ordered)}


def partition_maps(dataset: str, subjects: Iterable[object]) -> list[dict[str, int]]:
    salts = PARTITION_SALTS[dataset]
    maps = [partition_subjects(subjects, salt) for salt in salts]
    if maps[0] == maps[1]:
        raise RuntimeError(f"{dataset} partition systems are not independent")
    return maps


def normalize_trials(values: list[np.ndarray]) -> np.ndarray:
    arr = np.stack(values, axis=0).astype(np.float32, copy=True)
    arr = arr - arr.mean(axis=-1, keepdims=True)
    scale = arr.std(axis=-1, keepdims=True)
    return arr / np.maximum(scale, 1e-6)


def batch_tensor(data: DatasetData, positions: np.ndarray, device: torch.device) -> torch.Tensor:
    values = []
    for position in np.asarray(positions, dtype=int):
        row = data.frame.iloc[int(position)]
        path = str(row.signal_path) if str(row.signal_path) else None
        values.append(data.store.get(path, int(row.cache_index)))
    return torch.from_numpy(normalize_trials(values)).to(device)


def train_expert(data: DatasetData, train_positions: np.ndarray, expert: str, seed: int) -> StandardEEGNet:
    set_seed(seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = StandardEEGNet(data.channels).to(device)
    train_subject = data.frame.iloc[train_positions].subject.astype(str).to_numpy()
    domains_map = {s: i for i, s in enumerate(subject_ids(train_subject))}
    domains = np.asarray([domains_map[s] for s in train_subject], dtype=np.int64)
    domain_head = nn.Linear(model.representation_dim, max(2, len(domains_map))).to(device) if expert == "E1_GRL" else None
    parameters = list(model.parameters()) + (list(domain_head.parameters()) if domain_head is not None else [])
    optimizer = torch.optim.AdamW(parameters, lr=LR, weight_decay=WEIGHT_DECAY)
    labels = data.labels
    rng = np.random.default_rng(seed)
    for epoch in range(EPOCHS):
        order = rng.permutation(len(train_positions))
        factor = 0.05 + 0.95 * 0.5 * (1.0 + math.cos(math.pi * epoch / max(EPOCHS, 1)))
        for group in optimizer.param_groups:
            group["lr"] = LR * factor
        model.train()
        if domain_head is not None:
            domain_head.train()
        losses: list[float] = []
        for start in range(0, len(order), BATCH_SIZE):
            local = order[start : start + BATCH_SIZE]
            positions = train_positions[local]
            x = batch_tensor(data, positions, device)
            y = torch.as_tensor(labels[positions], dtype=torch.long, device=device)
            dom = torch.as_tensor(domains[local], dtype=torch.long, device=device)
            optimizer.zero_grad(set_to_none=True)
            autocast = torch.autocast(device_type="cuda", dtype=torch.bfloat16, enabled=device.type == "cuda")
            with autocast:
                h = model.forward_features(x)
                loss = F.cross_entropy(model.head(h), y)
                if expert == "E1_GRL":
                    assert domain_head is not None
                    loss = loss + GRL_COEF * F.cross_entropy(domain_head(GradientReverse.apply(h)), dom)
                elif expert == "E2_CORAL":
                    loss = loss + CORAL_COEF * coral_penalty(h, dom)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(parameters, 3.0)
            optimizer.step()
            losses.append(float(loss.detach().cpu()))
        if (epoch + 1) == 1 or (epoch + 1) % 5 == 0 or epoch + 1 == EPOCHS:
            print(f"[cpv2-train] {data.name} {expert} epoch={epoch + 1}/{EPOCHS} loss={np.mean(losses):.5f}", flush=True)
    model.eval()
    if domain_head is not None:
        del domain_head
    return model


def infer_expert(data: DatasetData, model: StandardEEGNet, positions: np.ndarray) -> np.ndarray:
    device = next(model.parameters()).device
    outputs: list[np.ndarray] = []
    with torch.inference_mode():
        for start in range(0, len(positions), BATCH_SIZE):
            batch = np.asarray(positions[start : start + BATCH_SIZE], dtype=int)
            outputs.append(model(batch_tensor(data, batch, device)).float().cpu().numpy())
    return np.concatenate(outputs, axis=0) if outputs else np.empty((0, 2), dtype=np.float32)


