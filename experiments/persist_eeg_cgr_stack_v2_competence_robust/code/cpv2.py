def competence_audit(dataset: str, data: dict[str, Any]) -> dict[str, Any]:
    margins = data["margins"]["E0_KEEP_ERM"]
    y = data["y"]
    subjects = data["subjects"]
    single_ba = [float(subject_ba(y, (margins[:, r] >= 0).astype(int), subjects).BA.mean()) for r in RUN_SLOTS]
    majority = (margins.mean(axis=1) >= 0).astype(int)
    six_mean = margins.mean(axis=1)
    majority_ba = float(subject_ba(y, majority, subjects).BA.mean())
    equal_ba = float(subject_ba(y, (six_mean >= 0).astype(int), subjects).BA.mean())
    calibration_t = fit_temperature(margins, y, subjects)
    calibrated_ba = float(subject_ba(y, (margins.mean(axis=1) / calibration_t >= 0).astype(int), subjects).BA.mean())
    error = (margins >= 0) != y[:, None]
    corr = []
    for i in range(6):
        for j in range(i + 1, 6):
            corr.append(float(np.corrcoef(error[:, i].astype(float), error[:, j].astype(float))[0, 1]))
    best_single = max(single_ba)
    # This is a preregistered competence sanity threshold, not a result-tuned
    # success gate: a binary EEG decoder must clear a modest margin above chance.
    competent = bool(best_single >= 0.55 and majority_ba >= 0.55 and np.isfinite(single_ba).all())
    return {
        "dataset": dataset,
        "subjects": int(len(subject_ids(subjects))),
        "single_run_BA": single_ba,
        "best_single_80pct_OOF_BA": best_single,
        "six_run_majority_BA": majority_ba,
        "six_run_mean_logit_BA": equal_ba,
        "calibrated_KEEP_ensemble_BA": calibrated_ba,
        "calibration_temperature": calibration_t,
        "run_error_pairwise_correlation_mean": float(np.mean(corr)),
        "run_error_pairwise_correlation_max": float(np.max(corr)),
        "nondegenerate_run_count": int(sum(0.05 < ba < 0.95 for ba in single_ba)),
        "competent": competent,
        "complete_case_filter": False,
        "S2_accessed": False,
        "outer_accessed": False,
    }


def consensus_audit(metric_by_dataset: dict[str, pd.DataFrame], details_by_dataset: dict[str, dict[str, Any]]) -> tuple[pd.DataFrame, dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    associations: dict[str, Any] = {}
    for dataset, details in details_by_dataset.items():
        data = details["data"]
        margins = data["margins"]["E0_KEEP_ERM"]
        groups, entropy, votes = instability_groups(margins)
        error = (margins.mean(axis=1) >= 0) != data["y"]
        rates = []
        for group in range(4):
            mask = groups == group
            rate = float(error[mask].mean()) if mask.any() else float("nan")
            rates.append(rate)
            rows.append({"dataset": dataset, "group": group, "vote_pattern": ["6-0", "5-1", "4-2", "3-3"][group], "n_samples": int(mask.sum()), "error_rate": rate, "mean_vote_entropy": float(entropy[mask].mean()) if mask.any() else float("nan"), "mean_margin_variance": float(np.var(margins[mask], axis=1).mean()) if mask.any() else float("nan"), "consensus_authorized": False})
        valid = np.isfinite(rates)
        rho, p = spearmanr(np.arange(4)[valid], np.asarray(rates)[valid]) if valid.sum() >= 3 else (float("nan"), float("nan"))
        subject_rows = []
        for sub in subject_ids(data["subjects"]):
            smask = data["subjects"] == sub
            per = [float(error[smask & (groups == g)].mean()) if np.any(smask & (groups == g)) else np.nan for g in range(4)]
            valid_s = np.isfinite(per)
            if valid_s.sum() >= 3:
                subject_rows.append(float(spearmanr(np.arange(4)[valid_s], np.asarray(per)[valid_s]).statistic))
        associations[dataset] = {"pooled_spearman_rho": float(rho), "pooled_p": float(p), "subject_level_spearman_mean": float(np.nanmean(subject_rows)) if subject_rows else float("nan"), "instability_error_association_meaningful": bool(np.isfinite(rho) and rho > 0.2)}
    return pd.DataFrame(rows), associations


def complementarity_audit(details_by_dataset: dict[str, dict[str, Any]], metrics: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for dataset, details in details_by_dataset.items():
        data = details["data"]
        y = data["y"]
        keep_pred = (details["predictions"]["STRONGEST_KEEP"] >= 0.5).astype(int)
        keep_error = keep_pred != y
        for expert in EXPERTS:
            ep = (data["margins"][expert].mean(axis=1) >= 0).astype(int)
            e_error = ep != y
            overlap = float(np.mean(keep_error & e_error))
            rescue = float(np.mean(e_error[keep_error] == 0)) if keep_error.any() else float("nan")
            harm = float(np.mean(e_error[~keep_error])) if (~keep_error).any() else float("nan")
            q_num = float(np.mean(keep_error & e_error) * np.mean(~keep_error & ~e_error) - np.mean(keep_error & ~e_error) * np.mean(~keep_error & e_error))
            rows.append({"dataset": dataset, "expert_family": expert, "individual_BA": float(subject_ba(y, ep, data["subjects"]).BA.mean()), "error_overlap_with_KEEP": overlap, "Q_statistic": q_num, "error_correlation": float(np.corrcoef(keep_error.astype(float), e_error.astype(float))[0, 1]), "double_fault_rate": overlap, "conditional_rescue_rate": rescue, "conditional_harm_rate": harm, "useful_nonzero_contribution": bool(rescue > harm)})
    return pd.DataFrame(rows)


