"""Post-lock evaluator for the one-fold GeoSR futility gate.

The gate is intentionally conservative: it can stop further compute, but a
positive result is explicitly marked provisional and cannot authorize a final
claim.  No outcome data are loaded until ``PRE_OUTCOME_FUTILITY_LOCK.json``
has been atomically written and re-read.
"""
from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import torch

import audit_primitives as ap
import run_geosr as g


METHODS = ("SUBJECT_BALANCED_ERM", "GEOSR")
SEED = 0
FOLD = 0

# This rule is written into the lock before labels are opened.  It is a
# futility rule only: it does not define a publishable positive result.
FUTILITY_RULE = {
    "stop_if_mean_delta_pp_le": 0.0,
    "stop_if_nonnegative_subject_fraction_lt": 0.50,
    "stop_if_material_harm_fraction_gt": 0.25,
    "positive_requires_all": True,
}


def clean(v: Any) -> Any:
    if isinstance(v, dict):
        return {str(k): clean(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [clean(x) for x in v]
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating, float)):
        x = float(v)
        return x if math.isfinite(x) else None
    if isinstance(v, (np.bool_,)):
        return bool(v)
    return v


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".part")
    tmp.write_text(json.dumps(clean(value), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)


def write_csv(path: Path, rows: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    frame = rows if isinstance(rows, pd.DataFrame) else pd.DataFrame(rows)
    tmp = path.with_suffix(path.suffix + ".part")
    frame.to_csv(tmp, index=False)
    tmp.replace(path)


def worker_lock(worker_root: Path) -> dict[str, Any]:
    lock_path = worker_root / "PRE_OUTCOME_GEOSR_DECISION_LOCK.json"
    if not lock_path.is_file():
        raise RuntimeError(f"worker pre-outcome lock missing: {lock_path}")
    lock = json.loads(lock_path.read_text(encoding="utf-8-sig"))
    if lock.get("outcome_labels_read") is not False:
        raise RuntimeError(f"worker lock already opened outcomes: {worker_root}")
    if lock.get("methods") != list(METHODS) or lock.get("folds") != [FOLD] or lock.get("datasets") != ["OpenBMI"]:
        raise RuntimeError(f"worker scope mismatch: {worker_root}")
    if int(lock.get("seed", -1)) != SEED or int(lock.get("inner_crossfit_k", -1)) != g.INNER_K:
        raise RuntimeError(f"worker seed/cross-fit mismatch: {worker_root}")
    if int(lock.get("descriptor_cap", -1)) != g.CAP:
        raise RuntimeError(f"worker descriptor cap mismatch: {worker_root}")
    if lock.get("WBCIC_outer_10_opened") is not False or lock.get("OpenBMI_outer_test_opened") is not False:
        raise RuntimeError(f"worker outer access flags invalid: {worker_root}")
    manifest = worker_root / "runtime" / "seed-0" / "PREFLIGHT_MANIFEST.json"
    if not manifest.is_file():
        raise RuntimeError(f"worker manifest missing: {manifest}")
    entry = json.loads(manifest.read_text(encoding="utf-8"))["OpenBMI/fold-0/seed-0"]
    for method in METHODS:
        p = Path(entry["checkpoints"][method]["path"])
        # Paths are generated by the runner; reject anything escaping the
        # worker root before loading a model.
        try:
            p.resolve().relative_to(worker_root.resolve())
        except ValueError as exc:
            raise RuntimeError(f"checkpoint path escapes worker root: {p}") from exc
        meta = g.checkpoint_meta_path(p)
        if not p.is_file() or not meta.is_file():
            raise RuntimeError(f"checkpoint/meta missing for {method}: {p}")
        payload = json.loads(meta.read_text(encoding="utf-8"))
        if payload.get("method") != method or payload.get("stage") != "final_refit" or payload.get("seed") != SEED:
            raise RuntimeError(f"checkpoint metadata mismatch for {method}: {p}")
    return {"lock": lock, "manifest": entry, "lock_sha256": g.file_sha(lock_path)}


def make_lock(root: Path, worker_root: Path) -> Path:
    info = worker_lock(worker_root)
    roles, _, _ = ap.load_roles("OpenBMI")
    role_hashes = [g.role_hash(r) for r in roles]
    lock = {
        "schema": "PERSIST_EEG_GEOSR_FUTILITY_PRE_OUTCOME_LOCK_V1",
        "created_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seed": SEED, "datasets": ["OpenBMI"], "folds": [FOLD],
        "methods": list(METHODS), "backbone": "EEGNet", "inner_crossfit_k": g.INNER_K,
        "descriptor_cap": g.CAP, "worker_lock_sha256": info["lock_sha256"],
        "worker_manifest": info["manifest"], "role_hashes": {"OpenBMI": role_hashes},
        "futility_rule": FUTILITY_RULE,
        "screen_only": True, "positive_claim_authorized": False,
        "outcome_labels_read": False, "canonical_outcome_indices_materialized": False,
        "WBCIC_outer_10_opened": False, "OpenBMI_outer_test_opened": False,
        "scientific_definition_changed": False,
        "code_sha256": g.file_sha(Path(g.__file__)),
        "audit_primitives_sha256": g.file_sha(Path(ap.__file__)),
    }
    path = root / "PRE_OUTCOME_FUTILITY_LOCK.json"
    write_json(path, lock)
    audit = {
        "schema": "PERSIST_EEG_GEOSR_FUTILITY_LEGALITY_V1", "seed": SEED,
        "datasets": ["OpenBMI"], "folds": [FOLD], "methods": list(METHODS),
        "WBCIC_outer_10_opened": False, "OpenBMI_outer_test_opened": False,
        "canonical_outcome_indices_materialized": False, "canonical_outcome_labels_read": False,
        "outcome_labels_read_before_lock": False, "outcome_labels_read_after_lock": False,
        "lock_sha256": g.file_sha(path), "role_hashes": {"OpenBMI": role_hashes},
    }
    write_json(root / "DATA_LEGALITY_AUDIT.json", audit)
    # Re-read and verify the atomic lock before any outcome loader is called.
    check = json.loads(path.read_text(encoding="utf-8"))
    if check.get("outcome_labels_read") is not False or check.get("screen_only") is not True:
        raise RuntimeError("futility lock verification failed")
    return path


def evaluate(root: Path, worker_root: Path) -> dict[str, Any]:
    lock_path = root / "PRE_OUTCOME_FUTILITY_LOCK.json"
    if not lock_path.is_file():
        raise RuntimeError("futility lock missing")
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    if lock.get("outcome_labels_read") is not False:
        raise RuntimeError("invalid futility lock")
    info = worker_lock(worker_root)
    if info["lock_sha256"] != lock.get("worker_lock_sha256"):
        raise RuntimeError("worker lock changed after futility lock")

    # This is the first and only call that materializes OpenBMI outer-fold
    # labels.  It occurs strictly after the lock check above.
    roles, _, _ = ap.load_roles("OpenBMI")
    role = roles[FOLD]
    rows: list[dict[str, Any]] = []
    data = ap.load_ab_data("OpenBMI", set(role["outcome"]))
    manifest = info["manifest"]
    for method in METHODS:
        ck = Path(manifest["checkpoints"][method]["path"])
        rows.extend([{**r, "method": method} for r in g.eval_checkpoint(data, ck, role["outcome"], "OpenBMI", FOLD, SEED, torch.device("cuda"))])
        data = ap.load_ab_data("OpenBMI", set(role["outcome"]))
    frame = pd.DataFrame(rows)
    write_csv(root / "results" / "OUTCOME_PER_SUBJECT.csv", frame)
    subj = frame.groupby(["dataset", "method", "subject_id"], as_index=False).agg(BA=("BA", "mean"), accuracy=("accuracy", "mean"), macro_F1=("macro_F1", "mean"), NLL=("NLL", "mean"))
    write_csv(root / "results" / "PERFORMANCE_SUMMARY.csv", subj.groupby(["dataset", "method"], as_index=False).agg(mean_subject_BA=("BA", "mean"), mean_accuracy=("accuracy", "mean"), mean_macro_F1=("macro_F1", "mean"), mean_NLL=("NLL", "mean"), n_subjects=("subject_id", "nunique")))
    base = subj[subj.method == "SUBJECT_BALANCED_ERM"].set_index("subject_id").BA
    geo = subj[subj.method == "GEOSR"].set_index("subject_id").reindex(base.index).BA
    delta = geo - base
    metrics = {
        "dataset": "OpenBMI", "fold": FOLD, "seed": SEED, "n_subjects": int(len(delta)),
        "geosr_mean_BA": float(geo.mean()), "sb_erm_mean_BA": float(base.mean()),
        "mean_delta_pp": float(delta.mean() * 100.0),
        "nonnegative_subject_fraction": float(np.mean(delta >= 0)),
        "material_harm_fraction": float(np.mean(delta <= -0.02)),
        "worst_subject_delta_pp": float(delta.min() * 100.0),
    }
    stop = bool(metrics["mean_delta_pp"] <= FUTILITY_RULE["stop_if_mean_delta_pp_le"] or
                metrics["nonnegative_subject_fraction"] < FUTILITY_RULE["stop_if_nonnegative_subject_fraction_lt"] or
                metrics["material_harm_fraction"] > FUTILITY_RULE["stop_if_material_harm_fraction_gt"])
    terminal = "FUTILITY_STOP_AFTER_OPENBMI_FOLD0" if stop else "FUTILITY_CONTINUE_WBCIC_AND_RANDOM"
    result = {
        "schema": "PERSIST_EEG_GEOSR_FUTILITY_RESULT_V1", "terminal": terminal,
        "continue": not stop, "screen_only": True, "positive_claim_authorized": False,
        "metrics": metrics, "rule": FUTILITY_RULE, "outcome_after_lock": True,
        "WBCIC_outer_10_opened": False, "scientific_definition_changed": False,
    }
    write_json(root / "results" / "FUTILITY_RESULT.json", result)
    write_json(root / "results" / "VALIDATION.json", {"pass": True, "screen_only": True, "outcome_after_lock": True, "outer_sealed_closed": True, "scientific_definition_changed": False, "terminal": terminal})
    lock.update({"outcome_labels_read": True, "canonical_outcome_indices_materialized": True, "outcome_evaluated_after_lock": True})
    write_json(root / "POST_OUTCOME_FUTILITY_AUDIT.json", {"lock_sha256": g.file_sha(lock_path), "outcome_labels_read_after_lock": True, "WBCIC_outer_10_opened": False, "OpenBMI_outer_test_opened": False})
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", choices=("lock", "outcome"), required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--worker-root", type=Path, required=True)
    args = parser.parse_args()
    args.root.mkdir(parents=True, exist_ok=True)
    if args.phase == "lock":
        path = make_lock(args.root.resolve(), args.worker_root.resolve())
        print(f"FUTILITY_PRE_OUTCOME_LOCKED {path}", flush=True)
    else:
        result = evaluate(args.root.resolve(), args.worker_root.resolve())
        print(result["terminal"], flush=True)


if __name__ == "__main__":
    main()
